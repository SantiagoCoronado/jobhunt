"""Harness-neutral role files and `sync-agents` (spec decision 7).

`prompts/agents/<role>.md` is the one place a role's system prompt lives: a small YAML
frontmatter (`name`, `description`, `tools` in the orchestrator's vocabulary, `output`, the
contract the unit must satisfy) and the body. `python -m src.hunt sync-agents` renders every
harness's native agent file from it (`NATIVE` below: one folder and one renderer per harness).
The generated files are committed so interactive use works after a clone, and `sync-agents
--check` (CI) fails when they drift from the role files or from the stage models in
`config/hunt.toml`. Never edit a generated file; edit the role file.

A model id means something only to the harness whose catalog it came from, so a generated
file carries the stage's `model` only when that stage runs on that file's harness.

Commands follow the same pattern (docs/spec-pre-release.md decision 4): `prompts/commands/
<name>.md` is the one source of a `/jh-*` command, `NATIVE_COMMANDS` renders it per harness
beside the agent files, and the same `--check` covers them.
"""
from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import yaml

from ..config import ROOT
from ..setup import HOME_SKILL_MARK
from .config import HuntConfig
from .harness import TOOL_ORDER, TOOLS

PROMPTS_DIR = ROOT / "prompts" / "agents"
AGENTS_ROOT = ROOT                     # the generated folders hang off the repo root (tests move it)
ROLE_STAGE: dict[str, str] = {
    "triager": "triage", "job-matcher": "match", "inbox-classifier": "inbox",
    "company-researcher": "research", "resume-tailor": "tailor",
}
_CLAUDE_TOOLS: dict[str, list[str]] = {
    "read": ["Read"], "write": ["Write"], "edit": ["Edit"], "bash": ["Bash"], "web": ["WebSearch", "WebFetch"],
}
_FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
GENERATED_MARK = "<!-- generated by `python -m src.hunt sync-agents` from prompts/agents/{name}.md; edit that file, not this one -->"


@dataclass(frozen=True)
class Role:
    name: str
    description: str
    tools: frozenset[str]
    output: str
    body: str
    path: Path

    @property
    def stage(self) -> str:
        return ROLE_STAGE[self.name]


def parse_role(path: Path) -> Role:
    text = path.read_text(encoding="utf-8")
    m = _FRONT.match(text)
    if not m:
        raise ValueError(f"{path}: missing the --- frontmatter block")
    try:
        front = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        raise ValueError(f"{path}: bad frontmatter: {e}") from e
    if not isinstance(front, dict):
        raise ValueError(f"{path}: frontmatter must be a mapping")
    unknown = sorted(set(front) - {"name", "description", "tools", "output"})
    if unknown:
        raise ValueError(f"{path}: unknown frontmatter key(s) {', '.join(unknown)}")
    name = str(front.get("name") or "")
    if name != path.stem:
        raise ValueError(f"{path}: name {name!r} must equal the file stem {path.stem!r}")
    if name not in ROLE_STAGE:
        raise ValueError(f"{path}: {name!r} is not a hunt role (known: {', '.join(ROLE_STAGE)})")
    description = str(front.get("description") or "").strip()
    if not description:
        raise ValueError(f"{path}: description is required")
    tools_raw = front.get("tools") or []
    if not isinstance(tools_raw, list):
        raise ValueError(f"{path}: tools must be a list from {', '.join(TOOL_ORDER)}")
    tools = frozenset(str(t) for t in tools_raw)
    bad = sorted(tools - TOOLS)
    if bad:
        raise ValueError(f"{path}: unknown tool(s) {', '.join(bad)} (known: {', '.join(TOOL_ORDER)})")
    output = str(front.get("output") or "").strip()
    if not output:
        raise ValueError(f"{path}: output (the contract line) is required")
    body = text[m.end():].strip("\n") + "\n"
    if "—" in body or "—" in description:
        raise ValueError(f"{path}: contains an em-dash")
    return Role(name, description, tools, output, body, path)


def load_roles(prompts_dir: Path | None = None) -> dict[str, Role]:
    prompts_dir = prompts_dir or PROMPTS_DIR
    roles = {p.stem: parse_role(p) for p in sorted(prompts_dir.glob("*.md"))}
    missing = sorted(set(ROLE_STAGE) - set(roles))
    if missing:
        raise ValueError(f"{prompts_dir}: missing role file(s) {', '.join(missing)}")
    return roles


def _stage_model(role: Role, cfg: HuntConfig, harness: str) -> str | None:
    """The stage's model, when the stage runs on `harness` (whose catalog it was picked from)."""
    return cfg.stage(role.stage).model if cfg.harness_for(role.stage) == harness else None


def render_claude(role: Role, cfg: HuntConfig) -> str:
    """The `.claude/agents/<role>.md` text: claude frontmatter (tools by their claude names,
    the stage's model from hunt.toml when one is set) and the body under a generated mark."""
    names = [n for t in TOOL_ORDER if t in role.tools for n in _CLAUDE_TOOLS[t]]
    lines = ["---", f"name: {role.name}", f"description: {role.description}"]
    if names:
        lines.append(f"tools: {', '.join(names)}")
    model = _stage_model(role, cfg, "claude")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


HUNT_PREFIX = "hunt-"      # `.opencode/agents/hunt-<role>.md`: the grant of the hunt's stage, see `hunt_grants`


def hunt_grants(roles: dict[str, Role]) -> dict[str, frozenset[str]]:
    """{role: the stage's tools} for every role whose hunt stage grants LESS than the role
    file (today the matcher: it keeps bash for interactive ingest, and under the orchestrator
    ingest is Python's, decision 13). claude, pi and codex narrow the grant on the command
    line; opencode applies tools only through an agent file, so those roles get a second file
    the hunt runs on, and the first stays what interactive use needs."""
    from .stages import REGISTRY                      # here, not at the top: stages.fan imports this module
    out: dict[str, frozenset[str]] = {}
    for stage in REGISTRY.values():
        if stage.role in roles and stage.tools < roles[stage.role].tools:
            out[stage.role] = stage.tools
    return out


def render_opencode(role: Role, cfg: HuntConfig, tools: frozenset[str] | None = None) -> str:
    """The `.opencode/agents/<role>.md` text (format checked on opencode 1.18.29: `opencode
    agent list` resolves these rules as written, the last matching pattern wins). The file
    name is the agent's name; `mode: all` lets `opencode run --agent` and an @mention both use
    it; `edit` is opencode's one permission for write and edit; `bash` is "python only".
    `tools` narrows the grant for the `hunt-<role>` file."""
    allow = {True: "allow", False: "deny"}
    description = role.description if tools is None else f"The hunt orchestrator's grant of {role.name} (a unit of `python -m src.hunt run`). {role.description}"
    role = role if tools is None else Role(role.name, description, tools, role.output, role.body, role.path)
    lines = ["---", f"description: {_yaml_str(role.description)}", "mode: all"]
    model = _stage_model(role, cfg, "opencode")
    if model:
        lines.append(f"model: {model}")
    lines += ["permission:", f"  read: {allow['read' in role.tools]}",
              f"  edit: {allow[bool(role.tools & {'write', 'edit'})]}"]
    if "bash" in role.tools:
        lines += ["  bash:", '    "*": deny', '    "python *": allow', '    ".venv/bin/python *": allow']
    else:
        lines.append("  bash: deny")
    lines += [f"  webfetch: {allow['web' in role.tools]}", f"  websearch: {allow['web' in role.tools]}"]
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


def render_pi(role: Role, cfg: HuntConfig) -> str:
    """The `.pi/agents/<role>.md` text, the frontmatter pi's subagent extensions document
    (`name`, `description`, `tools` as a comma list of pi's own tool names, `model`). Not
    checked against a loaded extension: none is installed here (2026-09-21). The hunt does
    not read these files, `hunt run` passes the body as `--system-prompt`; they are for
    interactive use. pi has no web tool, so a role's `web` has nothing to map to."""
    names = [t for t in TOOL_ORDER if t in role.tools and t != "web"]
    lines = ["---", f"name: {role.name}", f"description: {_yaml_str(role.description)}"]
    if names:
        lines.append(f"tools: {', '.join(names)}")
    model = _stage_model(role, cfg, "pi")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


_GEMINI_TOOLS: dict[str, list[str]] = {
    "read": ["read_file"], "write": ["write_file"], "edit": ["replace"], "bash": ["run_shell_command"],
    "web": ["google_web_search", "web_fetch"],
}


def render_gemini(role: Role, cfg: HuntConfig) -> str:
    """The `.gemini/agents/<role>.md` text: the Gemini CLI's documented local-subagent
    frontmatter (`name`, `description`, `kind: local`, `tools` by their Gemini names, `model`).
    Not checked against a loader: gemini 0.46.0 has no command that lists agents. gemini has
    no shipped adapter (spec decision 5: the generic template only), so a model is written
    only when a `[harness.gemini]` template runs the stage."""
    names = [n for t in TOOL_ORDER if t in role.tools for n in _GEMINI_TOOLS[t]]
    lines = ["---", f"name: {role.name}", f"description: {_yaml_str(role.description)}", "kind: local"]
    if names:
        lines += ["tools:", *(f"  - {n}" for n in names)]
    model = _stage_model(role, cfg, "gemini")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


def _toml_basic(text: str) -> str:
    """`text` as a TOML basic string: `tomllib` reads back exactly what went in."""
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    out = "".join(c if c >= " " or c in "\n\t" else f"\\u{ord(c):04x}" for c in out)
    return out.replace("\t", "\\t")


def render_codex(role: Role, cfg: HuntConfig) -> str:
    """The `.codex/agents/<role>.toml` text: codex's documented agent role (`name`,
    `description`, `developer_instructions`, `sandbox_mode`, `model`). Not checked against a
    loader: this codex is not logged in. The sandbox is codex's one grant, as in the adapter:
    workspace-write when the role may write, edit or run python, read-only otherwise."""
    sandbox = "workspace-write" if role.tools & {"write", "edit", "bash"} else "read-only"
    lines = ["# " + GENERATED_MARK.format(name=role.name).removeprefix("<!-- ").removesuffix(" -->"),
             f'name = "{_toml_basic(role.name)}"', f'description = "{_toml_basic(role.description)}"',
             f'sandbox_mode = "{sandbox}"']
    model = _stage_model(role, cfg, "codex")
    if model:
        lines.append(f'model = "{_toml_basic(model)}"')
    body = _toml_basic(role.body.rstrip("\n"))
    lines += [f'developer_instructions = """\n{body}\n"""', ""]
    return "\n".join(lines)


def _yaml_str(text: str) -> str:
    """A description as a YAML scalar that cannot be misread (a colon, a leading quote)."""
    return yaml.safe_dump(text, default_flow_style=True, width=10_000, allow_unicode=True).strip().removesuffix("...").strip()


# harness: (folder under the repo root, file suffix, renderer)
NATIVE: dict[str, tuple[str, str, Callable[[Role, HuntConfig], str]]] = {
    "claude": (".claude/agents", ".md", render_claude),
    "opencode": (".opencode/agents", ".md", render_opencode),
    "pi": (".pi/agents", ".md", render_pi),
    "gemini": (".gemini/agents", ".md", render_gemini),
    "codex": (".codex/agents", ".toml", render_codex),
}


# --- commands (docs/spec-pre-release.md decision 4) -------------------------------------------
#
# `prompts/commands/<name>.md` is the one place a `/jh-*` command lives: a small frontmatter
# (`description`, optional `argument-hint`, `tools` in the command vocabulary below, in the order
# the claude render lists them) and the body. `$ARGUMENTS` in the body is what the user typed
# after the command. `sync-agents` renders every command beside the agent files and `--check`
# covers both. Never edit a rendered command; edit its source.

COMMANDS_DIR = ROOT / "prompts" / "commands"
# the agent vocabulary plus what an interactive command may also use: `glob`, `agent` (the
# harness's own subagent) and the claude.ai Gmail connector, read-only or with draft creation
COMMAND_TOOLS: tuple[str, ...] = (*TOOL_ORDER, "glob", "agent", "gmail-read", "gmail-draft")
_CLAUDE_COMMAND_TOOLS: dict[str, list[str]] = {
    **_CLAUDE_TOOLS, "glob": ["Glob"], "agent": ["Task"],
    "gmail-read": ["mcp__claude_ai_Gmail__search_threads", "mcp__claude_ai_Gmail__get_thread",
                   "mcp__claude_ai_Gmail__get_message"],
    "gmail-draft": ["mcp__claude_ai_Gmail__create_draft"],
}
_EM_DASH = "\u2014"


@dataclass(frozen=True)
class Command:
    name: str
    description: str
    argument_hint: str | None
    tools: tuple[str, ...]
    body: str
    path: Path


def parse_command(path: Path) -> Command:
    text = path.read_text(encoding="utf-8")
    m = _FRONT.match(text)
    if not m:
        raise ValueError(f"{path}: missing the --- frontmatter block")
    try:
        front = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        raise ValueError(f"{path}: bad frontmatter: {e}") from e
    if not isinstance(front, dict):
        raise ValueError(f"{path}: frontmatter must be a mapping")
    unknown = sorted(set(front) - {"description", "argument-hint", "tools"})
    if unknown:
        raise ValueError(f"{path}: unknown frontmatter key(s) {', '.join(unknown)}")
    if not path.stem.startswith("jh-"):
        raise ValueError(f"{path}: a command's file name starts with jh-")
    description = str(front.get("description") or "").strip()
    if not description:
        raise ValueError(f"{path}: description is required")
    hint = front.get("argument-hint")
    tools_raw = front.get("tools") or []
    if not isinstance(tools_raw, list):
        raise ValueError(f"{path}: tools must be a list from {', '.join(COMMAND_TOOLS)}")
    tools = tuple(str(t) for t in tools_raw)
    bad = sorted(set(tools) - set(COMMAND_TOOLS))
    if bad:
        raise ValueError(f"{path}: unknown tool(s) {', '.join(bad)} (known: {', '.join(COMMAND_TOOLS)})")
    if len(set(tools)) != len(tools):
        raise ValueError(f"{path}: a tool is listed twice")
    body = text[m.end():]
    if any(_EM_DASH in s for s in (body, description, str(hint or ""))):
        raise ValueError(f"{path}: contains an em-dash")
    return Command(path.stem, description, None if hint is None else str(hint), tools, body, path)


def load_commands(commands_dir: Path | None = None) -> dict[str, Command]:
    commands_dir = commands_dir or COMMANDS_DIR
    return {p.stem: parse_command(p) for p in sorted(commands_dir.glob("*.md"))}


def _plain_or_quoted(text: str) -> str:
    """A frontmatter value written plain when YAML reads it back as the same string, else in
    double quotes (`[job_id]` would read as a list)."""
    try:
        same = yaml.safe_load(text) == text
    except yaml.YAMLError:
        same = False
    return text if same else '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


COMMAND_MARK = ("<!-- generated by `python -m src.hunt sync-agents` from prompts/commands/{name}.md; "
                "edit that file, not this one -->")


def _md_command(front: list[str], cmd: Command) -> str:
    """Frontmatter lines, the generated mark, then the body as written (it opens on a blank line)."""
    return "\n".join(["---", *front, "---", COMMAND_MARK.format(name=cmd.name)]) + "\n" + cmd.body


def render_claude_command(cmd: Command) -> str:
    """The `.claude/commands/<name>.md` text: claude's command frontmatter (`description`,
    `argument-hint`, `allowed-tools` by their claude names) and the body; claude substitutes
    `$ARGUMENTS` itself."""
    front = [f"description: {cmd.description}"]
    if cmd.argument_hint is not None:
        front.append(f"argument-hint: {_plain_or_quoted(cmd.argument_hint)}")
    if cmd.tools:
        front.append("allowed-tools: " + ", ".join(n for t in cmd.tools for n in _CLAUDE_COMMAND_TOOLS[t]))
    return _md_command(front, cmd)


def render_opencode_command(cmd: Command) -> str:
    """The `.opencode/commands/<name>.md` text. Format checked on opencode 1.18.29: `opencode
    debug config` lists the file under `command.<name>` with its `description` and the body as
    `template`. opencode substitutes `$ARGUMENTS`; it has no argument hint and no per-command
    tool list (the session's permissions apply), so neither is written."""
    return _md_command([f"description: {_yaml_str(cmd.description)}"], cmd)


def render_pi_command(cmd: Command) -> str:
    """The `.pi/prompts/<name>.md` text, a pi prompt template. Format checked on pi 0.85.1:
    its own `loadPromptTemplates` reads `.pi/prompts/*.md` (once the project is trusted) with
    `description` and `argument-hint`, and `substituteArgs` replaces `$ARGUMENTS`. A template
    has no tool list."""
    front = [f"description: {_yaml_str(cmd.description)}"]
    if cmd.argument_hint is not None:
        front.append(f"argument-hint: {_yaml_str(cmd.argument_hint)}")
    return _md_command(front, cmd)


GEMINI_ARGS = "{{args}}"
_GEMINI_INJECTIONS = ("!{", "@{", GEMINI_ARGS)


def render_gemini_command(cmd: Command) -> str:
    """The `.gemini/commands/<name>.toml` text. Format read from the loader itself
    (`FileCommandLoader` in the gemini-cli 0.46.0 bundle; gemini has no command that lists
    commands): a TOML file with `prompt` (required) and `description`, the name is the file
    stem, `{{args}}` is the argument placeholder, `!{...}` and `@{...}` inject shell output and
    files, so a body carrying either is refused. Loaded only in a trusted folder when folder
    trust is on."""
    hits = [s for s in _GEMINI_INJECTIONS if s in cmd.body]
    if hits:
        raise ValueError(f"{cmd.path}: {', '.join(hits)} would be read by gemini as an injection")
    body = cmd.body.replace("$ARGUMENTS", GEMINI_ARGS)
    mark = COMMAND_MARK.format(name=cmd.name).removeprefix("<!-- ").removesuffix(" -->")
    return "\n".join([f"# {mark}", f'description = "{_toml_basic(cmd.description)}"',
                      f'prompt = """{_toml_basic(body)}"""', ""])


# harness: (folder under the repo root, file suffix, renderer). codex and agy have no project
# command format (docs/hunt-harnesses.md): they get AGENTS.md, rendered by `render_agents_md`.
NATIVE_COMMANDS: dict[str, tuple[str, str, Callable[[Command], str]]] = {
    "claude": (".claude/commands", ".md", render_claude_command),
    "opencode": (".opencode/commands", ".md", render_opencode_command),
    "gemini": (".gemini/commands", ".toml", render_gemini_command),
    "pi": (".pi/prompts", ".md", render_pi_command),
}
AGENTS_MD_HARNESSES: tuple[str, ...] = ("codex", "agy")
AGENTS_MD = "AGENTS.md"
GUIDE = ROOT / "CLAUDE.md"              # the project guide AGENTS.md carries whole (render_agents_md)
FLOWS_HEADING = "The /jh-* flows"
_USAGE = re.compile(r"\s*Usage: /\S+.*\Z")


def command_say(cmd: Command) -> str:
    """What to type for a command where there is no slash command: the name and its hint."""
    return f"{cmd.name} {cmd.argument_hint}" if cmd.argument_hint else cmd.name


def render_agents_md(commands: dict[str, Command], guide: str | None = None) -> str:
    """`AGENTS.md` at the repo root: what codex and agy read for project instructions (both
    checked: `codex debug prompt-input` on 0.153.4 carries it; agy 1.2.8 documents it as its
    rules file). opencode (1.18.29) and pi read it too and then STOP: each takes the first of
    AGENTS.md / CLAUDE.md it finds, so a short AGENTS.md would hide the project guide from them.
    It is therefore the whole of `CLAUDE.md` (`guide`, read from `GUIDE` when None) followed by
    the flows under `## The /jh-* flows`, with the exact text to say where there is no slash command."""
    guide = GUIDE.read_text(encoding="utf-8") if guide is None else guide
    *head, last = list(NATIVE_COMMANDS)
    native = f"{', '.join(head)} and {last}"
    lines = [
        "<!-- generated by `python -m src.hunt sync-agents` from CLAUDE.md and prompts/commands/; edit those files, not this one -->",
        "",
        guide.rstrip("\n"),
        "",
        f"## {FLOWS_HEADING}",
        "",
        f"{native} have native `/jh-*` commands rendered from `prompts/commands/`. On",
        f"{' and '.join(AGENTS_MD_HARNESSES)}, the user says the text below instead. When a message starts with one of",
        "these names, with or without a leading `/` or `$`, read `prompts/commands/<name>.md` once and",
        "follow it: `$ARGUMENTS` in that file is the rest of the message, and its `tools:` line is what",
        "the flow needs (`bash` is your shell tool).",
        "",
    ]
    for cmd in commands.values():
        lines.append(f"- `{command_say(cmd)}`: {_USAGE.sub('', cmd.description)}")
    return "\n".join(lines) + "\n"




def render_home_skill(cmd: Command) -> str:
    """The opt-in home-level copy of a command for codex (`~/.codex/skills/<name>/SKILL.md`,
    checked: `codex debug prompt-input` on 0.153.4 lists a skill there; its old custom-prompts
    folder could not be found in that build). The body points at the command's source so a
    copy never goes stale; the installer writes it only where no foreign file stands."""
    return "\n".join([
        "---", f"name: {cmd.name}", f"description: {_yaml_str(_USAGE.sub('', cmd.description))}", "---",
        HOME_SKILL_MARK, "",
        "Use only inside a jobhunt checkout (a folder holding `prompts/commands/` and `src/hunt/`). Read",
        f"`prompts/commands/{cmd.name}.md` there once and follow it; `$ARGUMENTS` in that file is what the",
        f"user wrote after `{cmd.name}`.", ""])


def targets(cfg: HuntConfig, prompts_dir: Path | None = None, root: Path | None = None,
            commands_dir: Path | None = None) -> dict[Path, str]:
    """Every generated file and its expected content: each role for every harness in `NATIVE`,
    each command for every harness in `NATIVE_COMMANDS`."""
    root = root or AGENTS_ROOT
    roles = load_roles(prompts_dir)
    out = {root / folder / f"{role.name}{suffix}": render(role, cfg)
           for folder, suffix, render in NATIVE.values() for role in roles.values()}
    folder, suffix, _render = NATIVE["opencode"]
    for name, tools in hunt_grants(roles).items():
        out[root / folder / f"{HUNT_PREFIX}{name}{suffix}"] = render_opencode(roles[name], cfg, tools)
    commands = load_commands(commands_dir)
    for folder, suffix, render_command in NATIVE_COMMANDS.values():
        for cmd in commands.values():
            out[root / folder / f"{cmd.name}{suffix}"] = render_command(cmd)
    out[root / AGENTS_MD] = render_agents_md(commands)
    return out


def sync(cfg: HuntConfig, check: bool = False, prompts_dir: Path | None = None,
         root: Path | None = None, commands_dir: Path | None = None) -> tuple[list[str], list[str]]:
    """(written or drifted paths, unchanged paths). With `check`, nothing is written and the
    first list is what would change."""
    changed: list[str] = []
    same: list[str] = []
    for path, text in targets(cfg, prompts_dir, root, commands_dir).items():
        rel = str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            same.append(rel)
            continue
        changed.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return changed, same

"""Harness-neutral role files and `sync-agents` (spec decision 7).

`prompts/agents/<role>.md` is the one place a role's system prompt lives: a small YAML
frontmatter (`name`, `description`, `tools` in the orchestrator's vocabulary, `output`, the
contract the unit must satisfy) and the body. `python -m src.hunt sync-agents` renders every
harness's native agent file from it (`NATIVE` below: one folder and one renderer per harness).
The generated files are committed so interactive use works after a clone, and `sync-agents
--check` (CI) fails when they drift from the role files or from the stage models in
`config/hunt.toml`. Never edit a generated file; edit the role file.

A model id means something only to the harness whose catalog it came from, so a generated
file carries the stage's `model` only when that stage runs on that file's harness.
"""
from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import yaml

from ..config import ROOT
from .config import HuntConfig
from .harness import TOOL_ORDER, TOOLS

PROMPTS_DIR = ROOT / "prompts" / "agents"
AGENTS_ROOT = ROOT                     # the generated folders hang off the repo root (tests move it)
ROLE_STAGE: dict[str, str] = {
    "triager": "triage", "job-matcher": "match", "inbox-classifier": "inbox",
    "company-researcher": "research", "resume-tailor": "tailor",
}
_CLAUDE_TOOLS: dict[str, list[str]] = {
    "read": ["Read"], "write": ["Write"], "edit": ["Edit"], "bash": ["Bash"], "web": ["WebSearch", "WebFetch"],
}
_FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)
GENERATED_MARK = "<!-- generated by `python -m src.hunt sync-agents` from prompts/agents/{name}.md; edit that file, not this one -->"


@dataclass(frozen=True)
class Role:
    name: str
    description: str
    tools: frozenset[str]
    output: str
    body: str
    path: Path

    @property
    def stage(self) -> str:
        return ROLE_STAGE[self.name]


def parse_role(path: Path) -> Role:
    text = path.read_text(encoding="utf-8")
    m = _FRONT.match(text)
    if not m:
        raise ValueError(f"{path}: missing the --- frontmatter block")
    try:
        front = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        raise ValueError(f"{path}: bad frontmatter: {e}") from e
    if not isinstance(front, dict):
        raise ValueError(f"{path}: frontmatter must be a mapping")
    unknown = sorted(set(front) - {"name", "description", "tools", "output"})
    if unknown:
        raise ValueError(f"{path}: unknown frontmatter key(s) {', '.join(unknown)}")
    name = str(front.get("name") or "")
    if name != path.stem:
        raise ValueError(f"{path}: name {name!r} must equal the file stem {path.stem!r}")
    if name not in ROLE_STAGE:
        raise ValueError(f"{path}: {name!r} is not a hunt role (known: {', '.join(ROLE_STAGE)})")
    description = str(front.get("description") or "").strip()
    if not description:
        raise ValueError(f"{path}: description is required")
    tools_raw = front.get("tools") or []
    if not isinstance(tools_raw, list):
        raise ValueError(f"{path}: tools must be a list from {', '.join(TOOL_ORDER)}")
    tools = frozenset(str(t) for t in tools_raw)
    bad = sorted(tools - TOOLS)
    if bad:
        raise ValueError(f"{path}: unknown tool(s) {', '.join(bad)} (known: {', '.join(TOOL_ORDER)})")
    output = str(front.get("output") or "").strip()
    if not output:
        raise ValueError(f"{path}: output (the contract line) is required")
    body = text[m.end():].strip("\n") + "\n"
    if "—" in body or "—" in description:
        raise ValueError(f"{path}: contains an em-dash")
    return Role(name, description, tools, output, body, path)


def load_roles(prompts_dir: Path | None = None) -> dict[str, Role]:
    prompts_dir = prompts_dir or PROMPTS_DIR
    roles = {p.stem: parse_role(p) for p in sorted(prompts_dir.glob("*.md"))}
    missing = sorted(set(ROLE_STAGE) - set(roles))
    if missing:
        raise ValueError(f"{prompts_dir}: missing role file(s) {', '.join(missing)}")
    return roles


def _stage_model(role: Role, cfg: HuntConfig, harness: str) -> str | None:
    """The stage's model, when the stage runs on `harness` (whose catalog it was picked from)."""
    return cfg.stage(role.stage).model if cfg.harness_for(role.stage) == harness else None


def render_claude(role: Role, cfg: HuntConfig) -> str:
    """The `.claude/agents/<role>.md` text: claude frontmatter (tools by their claude names,
    the stage's model from hunt.toml when one is set) and the body under a generated mark."""
    names = [n for t in TOOL_ORDER if t in role.tools for n in _CLAUDE_TOOLS[t]]
    lines = ["---", f"name: {role.name}", f"description: {role.description}"]
    if names:
        lines.append(f"tools: {', '.join(names)}")
    model = _stage_model(role, cfg, "claude")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


HUNT_PREFIX = "hunt-"      # `.opencode/agents/hunt-<role>.md`: the grant of the hunt's stage, see `hunt_grants`


def hunt_grants(roles: dict[str, Role]) -> dict[str, frozenset[str]]:
    """{role: the stage's tools} for every role whose hunt stage grants LESS than the role
    file (today the matcher: it keeps bash for interactive ingest, and under the orchestrator
    ingest is Python's, decision 13). claude, pi and codex narrow the grant on the command
    line; opencode applies tools only through an agent file, so those roles get a second file
    the hunt runs on, and the first stays what interactive use needs."""
    from .stages import REGISTRY                      # here, not at the top: stages.fan imports this module
    out: dict[str, frozenset[str]] = {}
    for stage in REGISTRY.values():
        if stage.role in roles and stage.tools < roles[stage.role].tools:
            out[stage.role] = stage.tools
    return out


def render_opencode(role: Role, cfg: HuntConfig, tools: frozenset[str] | None = None) -> str:
    """The `.opencode/agents/<role>.md` text (format checked on opencode 1.18.29: `opencode
    agent list` resolves these rules as written, the last matching pattern wins). The file
    name is the agent's name; `mode: all` lets `opencode run --agent` and an @mention both use
    it; `edit` is opencode's one permission for write and edit; `bash` is "python only".
    `tools` narrows the grant for the `hunt-<role>` file."""
    allow = {True: "allow", False: "deny"}
    description = role.description if tools is None else f"The hunt orchestrator's grant of {role.name} (a unit of `python -m src.hunt run`). {role.description}"
    role = role if tools is None else Role(role.name, description, tools, role.output, role.body, role.path)
    lines = ["---", f"description: {_yaml_str(role.description)}", "mode: all"]
    model = _stage_model(role, cfg, "opencode")
    if model:
        lines.append(f"model: {model}")
    lines += ["permission:", f"  read: {allow['read' in role.tools]}",
              f"  edit: {allow[bool(role.tools & {'write', 'edit'})]}"]
    if "bash" in role.tools:
        lines += ["  bash:", '    "*": deny', '    "python *": allow', '    ".venv/bin/python *": allow']
    else:
        lines.append("  bash: deny")
    lines += [f"  webfetch: {allow['web' in role.tools]}", f"  websearch: {allow['web' in role.tools]}"]
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


def render_pi(role: Role, cfg: HuntConfig) -> str:
    """The `.pi/agents/<role>.md` text, the frontmatter pi's subagent extensions document
    (`name`, `description`, `tools` as a comma list of pi's own tool names, `model`). Not
    checked against a loaded extension: none is installed here (2026-09-21). The hunt does
    not read these files, `hunt run` passes the body as `--system-prompt`; they are for
    interactive use. pi has no web tool, so a role's `web` has nothing to map to."""
    names = [t for t in TOOL_ORDER if t in role.tools and t != "web"]
    lines = ["---", f"name: {role.name}", f"description: {_yaml_str(role.description)}"]
    if names:
        lines.append(f"tools: {', '.join(names)}")
    model = _stage_model(role, cfg, "pi")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


_GEMINI_TOOLS: dict[str, list[str]] = {
    "read": ["read_file"], "write": ["write_file"], "edit": ["replace"], "bash": ["run_shell_command"],
    "web": ["google_web_search", "web_fetch"],
}


def render_gemini(role: Role, cfg: HuntConfig) -> str:
    """The `.gemini/agents/<role>.md` text: the Gemini CLI's documented local-subagent
    frontmatter (`name`, `description`, `kind: local`, `tools` by their Gemini names, `model`).
    Not checked against a loader: gemini 0.46.0 has no command that lists agents. gemini has
    no shipped adapter (spec decision 5: the generic template only), so a model is written
    only when a `[harness.gemini]` template runs the stage."""
    names = [n for t in TOOL_ORDER if t in role.tools for n in _GEMINI_TOOLS[t]]
    lines = ["---", f"name: {role.name}", f"description: {_yaml_str(role.description)}", "kind: local"]
    if names:
        lines += ["tools:", *(f"  - {n}" for n in names)]
    model = _stage_model(role, cfg, "gemini")
    if model:
        lines.append(f"model: {model}")
    lines += ["---", "", GENERATED_MARK.format(name=role.name), "", role.body.rstrip("\n"), ""]
    return "\n".join(lines)


def _toml_basic(text: str) -> str:
    """`text` as a TOML basic string: `tomllib` reads back exactly what went in."""
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    out = "".join(c if c >= " " or c in "\n\t" else f"\\u{ord(c):04x}" for c in out)
    return out.replace("\t", "\\t")


def render_codex(role: Role, cfg: HuntConfig) -> str:
    """The `.codex/agents/<role>.toml` text: codex's documented agent role (`name`,
    `description`, `developer_instructions`, `sandbox_mode`, `model`). Not checked against a
    loader: this codex is not logged in. The sandbox is codex's one grant, as in the adapter:
    workspace-write when the role may write, edit or run python, read-only otherwise."""
    sandbox = "workspace-write" if role.tools & {"write", "edit", "bash"} else "read-only"
    lines = ["# " + GENERATED_MARK.format(name=role.name).removeprefix("<!-- ").removesuffix(" -->"),
             f'name = "{_toml_basic(role.name)}"', f'description = "{_toml_basic(role.description)}"',
             f'sandbox_mode = "{sandbox}"']
    model = _stage_model(role, cfg, "codex")
    if model:
        lines.append(f'model = "{_toml_basic(model)}"')
    body = _toml_basic(role.body.rstrip("\n"))
    lines += [f'developer_instructions = """\n{body}\n"""', ""]
    return "\n".join(lines)


def _yaml_str(text: str) -> str:
    """A description as a YAML scalar that cannot be misread (a colon, a leading quote)."""
    return yaml.safe_dump(text, default_flow_style=True, width=10_000, allow_unicode=True).strip().removesuffix("...").strip()


# harness: (folder under the repo root, file suffix, renderer)
NATIVE: dict[str, tuple[str, str, Callable[[Role, HuntConfig], str]]] = {
    "claude": (".claude/agents", ".md", render_claude),
    "opencode": (".opencode/agents", ".md", render_opencode),
    "pi": (".pi/agents", ".md", render_pi),
    "gemini": (".gemini/agents", ".md", render_gemini),
    "codex": (".codex/agents", ".toml", render_codex),
}


def targets(cfg: HuntConfig, prompts_dir: Path | None = None, root: Path | None = None) -> dict[Path, str]:
    """Every generated file and its expected content, for every harness in `NATIVE`."""
    root = root or AGENTS_ROOT
    roles = load_roles(prompts_dir)
    out = {root / folder / f"{role.name}{suffix}": render(role, cfg)
           for folder, suffix, render in NATIVE.values() for role in roles.values()}
    folder, suffix, _render = NATIVE["opencode"]
    for name, tools in hunt_grants(roles).items():
        out[root / folder / f"{HUNT_PREFIX}{name}{suffix}"] = render_opencode(roles[name], cfg, tools)
    return out


def sync(cfg: HuntConfig, check: bool = False, prompts_dir: Path | None = None,
         root: Path | None = None) -> tuple[list[str], list[str]]:
    """(written or drifted paths, unchanged paths). With `check`, nothing is written and the
    first list is what would change."""
    changed: list[str] = []
    same: list[str] = []
    for path, text in targets(cfg, prompts_dir, root).items():
        rel = str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            same.append(rel)
            continue
        changed.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return changed, same
